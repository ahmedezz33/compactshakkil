def get_stats():
    """إحصاءات القاموس."""
    from collections import Counter
    type_counter = Counter()
    letter_counter = Counter()

    for root, info in GOLD_HOLLOW_ROOTS.items():
        type_counter[info["type"]] += 1
        letter_counter[info["letter"]] += 1

    return {
        "total": len(GOLD_HOLLOW_ROOTS),
        "by_type": dict(type_counter),
        "by_letter": dict(letter_counter),
    }


def lookup(root_camel: str):
    """البحث عن جذر في القاموس المعياري."""
    return GOLD_HOLLOW_ROOTS.get(root_camel)


if __name__ == "__main__":
    stats = get_stats()
    print(f"إجمالي المدخلات: {stats['total']}")
    print(f"\nحسب النوع:")
    for t, c in sorted(stats["by_type"].items(), key=lambda x: -x[1]):
        print(f"  {t:20s} → {c}")
    print(f"\nحسب حرف العلّة:")
    for l, c in stats["by_letter"].items():
        print(f"  {l} → {c}")

    # اختبار
    print("\n--- اختبار ---")
    test_roots = ["ق.#.ل", "ب.#.ع", "#.ع.د", "د.ع.#", "ط.#.#"]
